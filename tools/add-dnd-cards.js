// rating 公式（与 tools/rating.js 一致）：血+攻+甲×3+词条/法术分值
const w = t => t === '拒马' ? 0.5 : (t === '飞行' || t === '远程' || t === '石像形态') ? 3
  : t.startsWith('法术护盾') ? (parseInt(t.slice(4), 10) || 1)
  : t.startsWith('再生') ? (parseInt(t.slice(2), 10) || 1)
  : t.startsWith('觉醒') ? 0 : 2;
function ratingOf(c) {
  if (c.type === 'spell') return 2;
  let r = (c.hp || 0) + (c.atk || 0) + (c.arm || 0) * 3;
  (c.traits || []).forEach(t => { r += w(t); });
  if (c.spell) r += 2;
  if (c.actSpell) r += 2;
  (c.actSpells || []).forEach(() => { r += 2; });
  return r;
}
